-- tests/3_planning/amm/test_waypoint_queue.lua
local waypoint_queue = require("waypoint_queue")

describe("Waypoint Queue and Persistence Logic", function()
    it("creates a new queue with default settings", function()
        local q = waypoint_queue.new({ defaultAlt = 120.0, defaultSpeed = 16.0, arrivalRadius = 15.0 })
        assert_not_nil(q)
        assert_eq(q:count(), 0)
        assert_eq(q.state, "IDLE")
        assert_nil(q:get_active())
    end)

    it("adds waypoints and auto-activates queue", function()
        local q = waypoint_queue.new({ defaultAlt = 100.0, defaultSpeed = 15.0 })
        local wp1 = q:add(100.0, 200.0)
        assert_not_nil(wp1)
        assert_eq(wp1.id, 1)
        assert_eq(wp1.x, 100.0)
        assert_eq(wp1.z, 200.0)
        assert_eq(wp1.alt, 100.0)
        assert_eq(wp1.speed, 15.0)
        assert_eq(q:count(), 1)
        assert_eq(q.state, "EN_ROUTE")

        local wp2 = q:add(300.0, 400.0, 150.0, 20.0, "PAD_01")
        assert_eq(wp2.id, 2)
        assert_eq(wp2.alt, 150.0)
        assert_eq(wp2.speed, 20.0)
        assert_eq(wp2.facilityId, "PAD_01")
        assert_eq(q:count(), 2)

        local active = q:get_active()
        assert_not_nil(active)
        assert_eq(active.id, 1)
    end)

    it("deletes waypoints and re-indexes remaining items", function()
        local q = waypoint_queue.new()
        q:add(10, 10)
        q:add(20, 20)
        q:add(30, 30)
        assert_eq(q:count(), 3)

        local ok = q:del(2)
        assert_true(ok)
        assert_eq(q:count(), 2)
        local all = q:get_all()
        assert_eq(all[1].x, 10)
        assert_eq(all[1].id, 1)
        assert_eq(all[2].x, 30)
        assert_eq(all[2].id, 2)
    end)

    it("clears all waypoints and resets to IDLE", function()
        local q = waypoint_queue.new()
        q:add(10, 20)
        q:add(30, 40)
        q:clear()
        assert_eq(q:count(), 0)
        assert_eq(q.state, "IDLE")
        assert_nil(q:get_active())
    end)

    it("advances active waypoint when within 2D arrival radius", function()
        local q = waypoint_queue.new({ arrivalRadius = 15.0 })
        q:add(100.0, 100.0)
        q:add(200.0, 200.0, 120.0, 18.0, "PAD_02")

        -- Craft far away: should not arrive
        local arrived, status, wp, dist = q:check_arrival({ x = 50.0, z = 100.0 })
        assert_false(arrived)
        assert_eq(status, "EN_ROUTE")
        assert_eq(wp.id, 1)
        assert_true(dist > 15.0)

        -- Craft within 10m of WP1: should arrive and advance to WP2
        local arrived2, status2, next_wp = q:check_arrival({ x = 95.0, z = 100.0 })
        assert_true(arrived2)
        assert_eq(status2, "ADVANCED")
        assert_not_nil(next_wp)
        assert_eq(next_wp.id, 2)
        assert_eq(q:get_active().id, 2)

        -- Craft within 5m of WP2: should complete mission
        local arrived3, status3, fin_wp = q:check_arrival({ x = 200.0, z = 202.0 })
        assert_true(arrived3)
        assert_eq(status3, "COMPLETED")
        assert_eq(fin_wp.id, 2)
        assert_eq(fin_wp.facilityId, "PAD_02")
        assert_eq(q.state, "COMPLETED")
    end)

    it("saves and loads v2.0.0 checkpoints[] route files cleanly and rejects v1.0.0 items[]", function()
        local q = waypoint_queue.new()
        q:add(500, -1200, 150, 18)
        q:add(800, -1500, 180, 20, "RUNWAY_01")

        local test_file = sdk.temp_path("test_route.json")
        local ok_save, err_save = q:save(test_file)
        assert_true(ok_save, err_save)

        local fh = fs.open(test_file, "r")
        local saved_tbl = textutils.unserializeJSON(fh.readAll())
        fh.close()
        assert_eq(saved_tbl.version, "2.0.0")
        assert_nil(saved_tbl.items)
        assert_not_nil(saved_tbl.checkpoints)

        local q2 = waypoint_queue.new()
        local ok_load, err_load = q2:load(test_file)
        assert_true(ok_load, err_load)
        assert_eq(q2:count(), 2)
        assert_eq(q2:get_active().x, 500)
        assert_eq(q2:get_all()[2].facilityId, "RUNWAY_01")

        -- Zero-Fallback: reject legacy v1.0.0 items[] schema
        local leg_file = sdk.temp_path("legacy_route.json")
        local lf = fs.open(leg_file, "w")
        lf.write(textutils.serializeJSON({ version = "1.0.0", items = { { id = 1, x = 10, z = 20 } } }))
        lf.close()
        local ok_leg, err_leg = q2:load(leg_file)
        assert_false(ok_leg)
        assert_eq(err_leg, "SCHEMA_INVALID")
    end)

    it("handles missing or corrupted JSON files gracefully", function()
        local q = waypoint_queue.new()
        local ok, err = q:load("non_existent_file.json")
        assert_false(ok)
        assert_not_nil(err)
    end)
end)
