describe("AMM Harness Setup and Configuration", function()
    it("loads default amm_config.json with correct defaults", function()
        local f = fs.open("config/amm_config.json", "r")
        assert_not_nil(f, "config/amm_config.json must exist")
        local raw = f.readAll()
        f.close()
        local cfg = textutils.unserializeJSON(raw)
        assert_not_nil(cfg, "config must parse as valid JSON")
        assert_eq(cfg.domainId, "AIRCRAFT_01")
        assert_eq(cfg.baseChannel, 10000)
        assert_eq(cfg.defaultAlt, 150.0)
        assert_eq(cfg.defaultSpeed, 18.0)
        assert_eq(cfg.arrivalRadius, 15.0)
        assert_eq(cfg.version, "1.3.0")
    end)
end)
